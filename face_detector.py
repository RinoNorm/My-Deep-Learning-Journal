import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle
from mtcnn import MTCNN
import tensorflow as tf

# Let's take a look at face recognition. We're using a convolutional neural network here, as you would with any neural network that works with images, but let's take it step by step.
# The origins of face recognition go back to the Viola–Jones algorithm. I won't go into too much detail about it, but the basic idea is worth mentioning.
# The algorithm takes a matrix of data and applies it to the image to find facial features. Together, these are called Haar features.
# However, we can improve this algorithm quite a bit by adding a convolutional neural network.
data = tf.io.read_file("photo.png")  # We load the image. The people in it were generated by a neural network.
image = tf.io.decode_png(data, channels=3).numpy()  # We convert the image to RGB.
fig, ax = plt.subplots(figsize=(12, 8), subplot_kw={"xticks": [], "yticks": []})
ax.imshow(image)
detector = MTCNN()  # Here we create a convolutional neural network made up of three different CNNs that run in sequence: P-Net, R-Net, and O-Net.
# One important detail: each network checks the regions that the previous one selected.
# P-Net, for example, looks like this: input (12 × 12 × 3) -> convolution (3 × 3) -> convolution (3 × 3) -> convolution (3 × 3) -> recognition based on features.
# Next come R-Net and O-Net, which recognize more features.
faces = detector.detect_faces(image)  # This is where the data goes through the network.
for face in faces:  # Here we mark all the faces found in the image.
    x, y, w, h = face["box"]
    rect = Rectangle((x, y), w, h, color="red", fill=False, lw=2)
    ax.add_patch(rect)
plt.show()
